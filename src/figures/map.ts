const BODY_FALLBACK: Record<Exercise['bodyPart'], string> = {
  shoulders: 'overheadFront',
  chest: 'highPlank',
  back: 'row',
  triceps: 'overheadExt',
  biceps: 'curl',
  wrists: 'wristFwd',
  abs: 'plank',
  legs: 'squat',
};

export function poseNameFor(ex: Exercise): string {
  const e = MAP[ex.id];
  const name = Array.isArray(e) ? e[0] : e;
  return name && POSES[name] ? name : BODY_FALLBACK[ex.bodyPart];
}

export function hasExplicitPose(id: string): boolean {
  const e = MAP[id];
  const name = Array.isArray(e) ? e[0] : e;
  return !!name && !!POSES[name];
}

const cache = new Map<string, Figure>();

export function figureFor(ex: Exercise): Figure {
  const hit = cache.get(ex.id);
  if (hit) return hit;
  const e = MAP[ex.id];
  const pose = { ...POSES[poseNameFor(ex)], ...(Array.isArray(e) ? e[1] : {}) };
  const eq = new Set(ex.equipment);
  const fig = buildFigure(pose, {
    dumbbells: eq.has('dumbbells'),
    bands: eq.has('bands'),
    medball: eq.has('medball'),
    abwheel: eq.has('abwheel'),
    gymball: eq.has('gymball'),
    wall: eq.has('wall'),
  });
  cache.set(ex.id, fig);
  return fig;
}
